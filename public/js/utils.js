export function escapeHtml(str) {
  return String(str ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function inr(n) {
  return '₹' + Math.round(Number(n) || 0).toLocaleString('en-IN');
}

export function normalizePhone(phone) {
  const digits = String(phone || '').replace(/\D/g, '');
  if (digits.length === 12 && digits.startsWith('91')) return digits.slice(2);
  return digits.slice(-10);
}

export function formatPhone(phone) {
  const p = normalizePhone(phone);
  return p.length === 10 ? `${p.slice(0, 5)} ${p.slice(5)}` : String(phone || '');
}

export function todayIso() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

export function formatDisplayDate(iso) {
  if (!iso || !/^\d{4}-\d{2}-\d{2}$/.test(iso)) return iso || '';
  if (iso === todayIso()) return 'Today';
  return new Date(`${iso}T00:00:00`).toLocaleDateString('en-IN', { day: 'numeric', month: 'short' });
}

export function av(name, colorIdx = 0, size = 38) {
  const initial = escapeHtml((String(name || '?').trim()[0] || '?').toUpperCase());
  const bg = COL[Math.abs(colorIdx) % COL.length];
  const fg = COF[Math.abs(colorIdx) % COF.length];
  return `<i class="av" aria-hidden="true" style="width:${size}px;height:${size}px;background:${bg};color:${fg};font-size:${Math.round(size * 0.38)}px">${initial}</i>`;
}

export function chip(text, cls = '') {
  return `<span class="chip ${cls}">${escapeHtml(text)}</span>`;
}

export function formatRating(val) {
  const num = Number(val);
  const safe = Number.isFinite(num) && num > 0 ? num : 4.9;
  return safe.toFixed(2);
}

export function ratingBadge(val) {
  const txt = formatRating(val);
  return `<span class="chip rating-pill tab-num" aria-label="Rating ${escapeHtml(txt)} out of 5">${STAR_SVG}<span>${escapeHtml(txt)}</span></span>`;
}

export function buildWaUrl(phone, message) {
  const p = normalizePhone(phone);
  return `https://wa.me/91${p}?text=${encodeURIComponent(message)}`;
}

export function parseServicesJson(raw) {
  if (Array.isArray(raw)) return raw;
  if (!raw) return [];
  try {
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch (_) {
    return [];
  }
}

